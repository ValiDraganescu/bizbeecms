#!/usr/bin/env node
/**
 * Bundle the design-system library (design-systems/<slug>/DESIGN.md) into
 * src/lib/chat/design-systems.generated.ts so the Worker can serve it (no
 * filesystem at runtime). The DESIGN.md files are the source of truth — edit
 * them, rerun this (it also runs on prebuild), and commit both. A freshness
 * check in scripts/design-systems.test.mjs fails when they drift.
 *
 * Frontmatter parsing is deliberately minimal: `name:` (one line) and
 * `description:` (one line, or a `>-`/`|` block scalar) — the full YAML is
 * shipped verbatim inside `content` for consumers that parse tokens.
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIB_DIR = join(ROOT, "design-systems");
const OUT_FILE = join(ROOT, "src", "lib", "chat", "design-systems.generated.ts");

export function parseFrontmatter(md) {
  const m = md.match(/^---\n([\s\S]*?)\n---/);
  if (!m) return {};
  const lines = m[1].split("\n");
  const out = {};
  for (let i = 0; i < lines.length; i++) {
    const kv = lines[i].match(/^(name|description):\s*(.*)$/);
    if (!kv) continue;
    let value = kv[2].trim();
    if (value === ">-" || value === ">" || value === "|" || value === "|-") {
      const block = [];
      while (i + 1 < lines.length && /^\s+\S/.test(lines[i + 1])) {
        block.push(lines[++i].trim());
      }
      value = block.join(" ");
    }
    out[kv[1]] = value.replace(/^["']|["']$/g, "");
  }
  return out;
}

export function buildRegistry(libDir) {
  const systems = [];
  for (const slug of readdirSync(libDir).sort()) {
    const file = join(libDir, slug, "DESIGN.md");
    if (!existsSync(file)) continue;
    const content = readFileSync(file, "utf8");
    const fm = parseFrontmatter(content);
    if (!fm.name) throw new Error(`${file}: frontmatter has no name:`);
    if (!fm.description) throw new Error(`${file}: frontmatter has no description:`);
    systems.push({ slug, name: fm.name, description: fm.description, content });
  }
  if (!systems.length) throw new Error(`no design systems found under ${libDir}`);
  return systems;
}

export function renderModule(systems) {
  const rows = systems
    .map(
      (s) =>
        `  {\n    slug: ${JSON.stringify(s.slug)},\n    name: ${JSON.stringify(s.name)},\n` +
        `    description: ${JSON.stringify(s.description)},\n    content: ${JSON.stringify(s.content)},\n  },`,
    )
    .join("\n");
  return (
    `// GENERATED by scripts/generate-design-systems.mjs from design-systems/*/DESIGN.md.\n` +
    `// Do not edit — edit the DESIGN.md files and rerun the script (runs on prebuild).\n\n` +
    `export type DesignSystem = {\n  slug: string;\n  name: string;\n  description: string;\n  content: string;\n};\n\n` +
    `export const DESIGN_SYSTEMS: readonly DesignSystem[] = [\n${rows}\n];\n`
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const module_ = renderModule(buildRegistry(LIB_DIR));
  writeFileSync(OUT_FILE, module_);
  console.log(`wrote ${OUT_FILE}`);
}
